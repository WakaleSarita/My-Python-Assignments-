### Write a program to calculate area of rectangle based on length and breadth. 
# Ans:-
# Area of Ractangle = Length * Breadth

# Take input for user

Length = int(input(' Enter Length of Rectangle is : '))
Breadth = int(input(' Enter Bredth of Rectangle is : '))
 
# Perform operation.

Area_of_Rectangle = Length * Breadth 

# Display result.

print('Area of Rectangle is : ', Area_of_Rectangle)