### Write a program to the input of two angles from users and find Third angle of traingle .

# Third Angle = 180 - (Angle 1 + Angle 2)
# Or
# A1 + A2 + A3 =180

# Take input of two angles for user

Angle_1 = int(input('Enter Angle First : '))
Angle_2 = int(input('Enter Angle second : '))

# Perform Operation 

Angle_3 = 180 - (Angle_1 + Angle_2)

# Display Result

print('Third angle of traingle is : ', Angle_3)



