### Write a program to calculate area of equilateral triangle.

# Area of Equilateral Traigle = Square root 3/4 * a**2 

# Take input from user

a = int(input('Enter Value of a : '))

# Perform operation

Area = (3 * 0.5 / 4 ) * a ** 2 

# Display Result

print('Area of Equilateral Triangle is : ', Area)
