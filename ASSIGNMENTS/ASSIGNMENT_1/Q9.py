### Write a programe to enter base and height of a triangle and find its area.

# Area of Triangle = 1/2 * base * height

# Take input values for users

Base = int(input('Enter base value is :'))
Height = int(input('Enter value height is : '))

# Calculate the values

Area = 1 / 2 * Base * Height

# Display result 

print('Area of Triangle is : ', Area)


